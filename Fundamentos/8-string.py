movieName = "The Matrix"
movieDescription = """A computer hacker learns ,from mysterious rebels about the true nature, of his reality and his role in " \
"the war against, its controllers."""

print(movieName.upper()) # Tudo maiúsculo
print(movieName.lower()) # Tudo minúsculo
print(movieDescription.title()) # Primeira letra maiscula e o restante minusculo
print(movieName.capitalize()) # Primeira letra maiscula e o restante minusculo
print(movieName.center(10, "*")) # Retorma a string centralizada com caractere de preenchimento "*".
print(movieName.find("a")) # Retorna o indice da letra  "u".
print(movieName.find("t")) # Conta caracteres a partir do inicio da string e retorna o indice da letra "t".
print(movieName.replace("The","Matrix")) # Altera o elemento por outro elemento.
print(movieDescription.split(" ")) # Retorna uma lista com os elementos separados por espaço.









